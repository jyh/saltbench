#!/usr/bin/env python3
"""The complete-pilot-matrix table of the paper, derived and checked rather than typed.

WHY THIS EXISTS
---------------
Section "The complete pilot matrix" of paper/saltbench-v1.tex prints twenty rows, one per
(model, task form, treatment), each carrying its DONE / INEXPRESSIBLE / DECLARED counts and the
result of record those counts rest on. Every row is a reading of the matrix census
(harness/systems-v3/CENSUS-full-matrix-2026-09-14.md) and its dated addenda, and a table typed
by hand from a 1,300-line census is a table nobody can audit.

This script holds the twenty rows with the census section each was read from, checks that
their sums equal the census's own LIVE row (parsed from the census file's bytes, never typed
here), checks the per-row arithmetic (every row is ten conditions; a statement row carries
Paxos's two inexpressible conditions), and prints the LaTeX rows. With --check it extracts
the rows between the markers in the tex and refuses if they differ from what it derives, so
the tex cannot drift from the census without a red. --self-test plants a wrong count and
requires the refusal to fire.

WHAT IT DOES NOT DO
-------------------
It does not read the result files. Which conditions each result of record covers is the
census's claim (its section C6 item 1 says the census is built from each result's own
population statement), and this script inherits that claim with its citation.
"""
