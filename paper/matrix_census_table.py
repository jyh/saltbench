LIVE_RE = re.compile(
    r"LIVE \(ADDENDUM (\d+)\)\s+DONE (\d+) · OWED\s+(\d+) · BLOCKED\s+(\d+) · INEXPR (\d+) · DECLARED (\d+)"
)


def census_live(path):
    """The census's own LIVE row, from its bytes. Refuses if there is not exactly one."""
    with open(path, "rb") as fh:
        text = fh.read().decode("utf-8")
    hits = LIVE_RE.findall(text)
    if len(hits) != 1:
        raise SystemExit("REFUSE: expected exactly one LIVE row in the census, found %d" % len(hits))
    add, done, owed, blocked, inexpr, declared = (int(x) for x in hits[0])
    return {"addendum": add, "done": done, "owed": owed, "blocked": blocked,
            "inexpr": inexpr, "declared": declared}


def check_rows(rows, live):
    problems = []
    if len(rows) != 20:
        problems.append("row count %d, expected 20 (4 models x 5 form-treatment pairs)" % len(rows))
    for m, f, t, d, i, x, files, sec in rows:
        if d + i + x != 10:
            problems.append("row %s/%s/%s sums to %d, not 10" % (m, f, t, d + i + x))
        if (t == "statement") != (i == 2):
            problems.append("row %s/%s/%s: only a statement row carries Paxos's 2 inexpressible" % (m, f, t))
        for name in files:
            p = os.path.join(ROOT, "harness", "systems-v3", "RESULT-%s.md" % name)
            if not os.path.isfile(p):
                problems.append("row %s/%s/%s cites a file that does not exist: %s" % (m, f, t, p))
    done = sum(r[3] for r in rows)
    inexpr = sum(r[4] for r in rows)
    declared = sum(r[5] for r in rows)
    for key, mine in (("done", done), ("inexpr", inexpr), ("declared", declared)):
        if mine != live[key]:
            problems.append("table %s = %d, census LIVE row %s = %d" % (key, mine, key, live[key]))
    if live["owed"] != 0 or live["blocked"] != 0:
        problems.append("census LIVE row still carries OWED %d / BLOCKED %d; the table has no column for them"
                        % (live["owed"], live["blocked"]))
    if done + inexpr + declared + live["owed"] + live["blocked"] != 200:
        problems.append("states do not sum to 200")
    return problems


def latex_rows(rows):
    out = []
    last_model = None
    for m, f, t, d, i, x, files, sec in rows:
        model = r"\texttt{%s}" % m if m != last_model else ""
        last_model = m
        cite = r"\newline ".join(r"\texttt{%s}" % name for name in files)
        out.append("%s & %s & %s & %d & %d & %d & %s \\\\" % (model, f, t, d, i, x, cite))
    done = sum(r[3] for r in rows)
    inexpr = sum(r[4] for r in rows)
    declared = sum(r[5] for r in rows)
    out.append(r"\midrule")
    out.append(r"all four models & & & %d & %d & %d & 200 conditions \\" % (done, inexpr, declared))
    return "\n".join(out)


def tex_block(path):
    with open(path, "rb") as fh:
        text = fh.read().decode("ascii")
    a = text.count(BEGIN)
    b = text.count(END)
    if a != 1 or b != 1:
        raise SystemExit("REFUSE: expected one BEGIN and one END marker in the tex, found %d and %d" % (a, b))
    start = text.index(BEGIN) + len(BEGIN)
    end = text.index(END)
    return text[start:end].strip()


def norm(s):
    return re.sub(r"\s+", " ", s.strip())


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--census", default=CENSUS)
    ap.add_argument("--check", metavar="TEX", nargs="?", const=TEX,
                    help="compare the rows in the tex against the derived rows; red on any difference")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args(argv)

    live = census_live(args.census)
    if args.self_test:
        bad = [list(r) for r in ROWS]
        bad[0][3] = 9
        bad = [tuple(r) for r in bad]
        p = check_rows(bad, live)
        if not any("table done" in x for x in p) or not any("sums to 9" in x for x in p):
            raise SystemExit("SELF-TEST FAIL: a planted wrong count was not refused: %r" % p)
        if check_rows(ROWS, live):
            raise SystemExit("SELF-TEST FAIL: the real rows do not pass: %r" % check_rows(ROWS, live))
        print("self-test OK: a planted wrong count is refused, the real rows pass, LIVE = ADDENDUM %d"
              % live["addendum"])
        return 0

    problems = check_rows(ROWS, live)
    if problems:
        for p in problems:
            print("REFUSE:", p)
        return 1
    generated = latex_rows(ROWS)
    if args.check:
        block = tex_block(args.check)
        if norm(block) != norm(generated):
            print("REFUSE: the table in %s differs from the derived rows" % args.check)
            print("--- derived\n%s\n--- in the tex\n%s" % (generated, block))
            return 1
        print("OK: the tex table equals the derived rows; totals DONE %d INEXPR %d DECLARED %d = census LIVE (ADDENDUM %d)"
              % (live["done"], live["inexpr"], live["declared"], live["addendum"]))
        return 0
    print(generated)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
